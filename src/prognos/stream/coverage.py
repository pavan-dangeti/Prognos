"""Live coverage monitoring against S5.

`docs/design.md` §4.4 sets S5: interval coverage in production stays within five
percentage points of the 90% target. That check does not exist anywhere else in this
project. The offline coverage in `results/phase4_policy.json` was measured on engines
the model had never seen, on data generated by the same simulator that trained it. A
model with 90% offline coverage and 71% live coverage is a degraded system, and
without this module nothing in the pipeline would notice.

Three design choices are load-bearing.

**The monitor judges coverage, not accuracy.** A drift that widens every interval
keeps coverage at target while telling an operator nothing about whether the
predictions are any good, so point error is tracked alongside as context rather than
as the trigger.

**It judges per engine, not in aggregate.** Aggregate coverage can sit at 90% while
one engine is chronically uncovered. Aggregate is reported because it is the S5
definition, and per-engine is reported because that is where the failure hides.

**The verdict needs a sample floor.** After three predictions the empirical coverage
is a coin flip, and declaring a breach from it would page someone about noise. The
floor is stated and the monitor says "not enough data" rather than guessing.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass, field

import numpy as np
import numpy.typing as npt

#: Minimum scored predictions before a verdict is issued at all.
MIN_SAMPLES = 50


@dataclass(frozen=True, slots=True)
class Observation:
    """One scored interval."""

    unit: int
    truth: float
    lower: float
    upper: float
    point: float


@dataclass(slots=True)
class CoverageVerdict:
    """What the monitor currently believes about calibration."""

    measured: float | None
    target: float
    tolerance: float
    n_samples: int
    status: str
    worst_engine: int | None = None
    worst_coverage: float | None = None

    @property
    def is_breach(self) -> bool:
        """Whether coverage has fallen outside the tolerance."""
        return self.status == "breach"

    def to_dict(self) -> dict[str, object]:
        """For the metrics endpoint and the dashboard."""
        return {
            "measured_coverage": self.measured,
            "target_coverage": self.target,
            "tolerance": self.tolerance,
            "n_samples": self.n_samples,
            "status": self.status,
            "worst_engine": self.worst_engine,
            "worst_engine_coverage": self.worst_coverage,
        }


@dataclass(slots=True)
class CoverageMonitor:
    """Rolling coverage over recent scored predictions, judged against S5.

    Holds a bounded window rather than a running count: coverage that has been broken
    for a week should still read as broken, and a lifetime average would slowly
    dilute the breach back into compliance.
    """

    target: float = 0.9
    tolerance: float = 0.05
    # Large enough to span a fleet. At 2000 the window held less than a
    # single engine's predictions, so the reported 'fleet' coverage was
    # whichever engine happened to finish last.
    history: int = 100_000
    observations: deque[Observation] = field(default_factory=deque)
    min_samples: int = MIN_SAMPLES

    def __post_init__(self) -> None:
        """Validate the tolerance before any observation arrives."""
        if not 0.0 < self.target < 1.0:
            raise ValueError(f"target coverage must be in (0, 1), got {self.target}")
        if not 0.0 < self.tolerance < 1.0:
            raise ValueError(f"tolerance must be in (0, 1), got {self.tolerance}")
        if self.history < self.min_samples:
            raise ValueError(
                f"history {self.history} is below the sample floor {self.min_samples}, "
                "so the monitor could never reach a verdict"
            )
        # Bounded so a week-old breach keeps reading as a breach. A lifetime average
        # would slowly dilute it back into compliance.
        self.observations = deque(self.observations, maxlen=self.history)

    def record(self, observation: Observation) -> None:
        """Add one scored interval, evicting the oldest if the window is full."""
        self.observations.append(observation)

    def verdict(self) -> CoverageVerdict:
        """Current coverage against the target, or an explicit refusal to judge.

        Reports a breach for a coverage *below* the tolerance band. Coverage above
        the target is not a breach — over-covering is wasteful, not dangerous — so
        it is reported as `ok` with the number attached for an operator to read.
        """
        # One snapshot, taken once. The replay thread appends while the dashboard
        # thread reads, and iterating the live deque raised "mutated during iteration"
        # as a 500 on /coverage. Copying a deque to a list is a single C call, so the
        # snapshot is consistent even with the writer running.
        observations = list(self.observations)
        n = len(observations)
        if n < self.min_samples:
            return CoverageVerdict(
                measured=None,
                target=self.target,
                tolerance=self.tolerance,
                n_samples=n,
                status="insufficient_data",
            )

        truths = np.asarray([o.truth for o in observations], dtype=np.float64)
        lowers = np.asarray([o.lower for o in observations], dtype=np.float64)
        uppers = np.asarray([o.upper for o in observations], dtype=np.float64)
        covered = (truths >= lowers) & (truths <= uppers)
        measured = float(np.mean(covered))

        status = "breach" if measured < self.target - self.tolerance else "ok"

        worst_unit, worst_coverage = self._worst_engine(observations, covered)
        return CoverageVerdict(
            measured=measured,
            target=self.target,
            tolerance=self.tolerance,
            n_samples=n,
            status=status,
            worst_engine=worst_unit,
            worst_coverage=worst_coverage,
        )

    def _worst_engine(
        self, observations: list[Observation], covered: npt.NDArray[np.bool_]
    ) -> tuple[int | None, float | None]:
        """The engine with the lowest coverage, ignoring engines with too little data.

        Aggregate coverage can sit at target while one engine is chronically
        uncovered. A single engine's rate is meaningless below the same floor, so
        those are excluded rather than allowed to drag the worst-case figure to zero.
        """
        by_unit: dict[int, list[bool]] = {}
        for observation, flag in zip(observations, covered, strict=True):
            by_unit.setdefault(observation.unit, []).append(bool(flag))
        eligible = {
            unit: float(np.mean(flags))
            for unit, flags in by_unit.items()
            if len(flags) >= self.min_samples
        }
        if not eligible:
            return None, None
        worst = min(eligible, key=lambda unit: eligible[unit])
        return worst, eligible[worst]

    def error_by_engine(self) -> dict[int, float]:
        """Mean absolute error per engine, for context alongside the coverage verdict."""
        errors: dict[int, list[float]] = {}
        for observation in list(self.observations):
            errors.setdefault(observation.unit, []).append(
                abs(observation.truth - observation.point)
            )
        return {unit: float(np.mean(values)) for unit, values in errors.items()}
