class TestObservability:
    def test_log_lines_are_single_line_json(self) -> None:
        """One log record per line, so `jq` and the shipper both work."""
        import io
        import logging

        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(JsonLogFormatter(service="inference"))
        logger = logging.getLogger("prognos.test.json")
        logger.handlers = [handler]
        logger.setLevel(logging.INFO)
        logger.propagate = False
        log_event(logger, "prediction.served", unit=1, rul=42.0)
        for line in stream.getvalue().splitlines():
            json.loads(line)

    def test_every_log_line_carries_a_request_id(self) -> None:
        """Without a request id, a prediction cannot be traced back to its input."""
        import io
        import logging

        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(JsonLogFormatter(service="inference"))
        logger = logging.getLogger("prognos.test.request")
        logger.handlers = [handler]
        logger.setLevel(logging.INFO)
        logger.propagate = False
        log_event(logger, "prediction.served", unit=1)
        record = json.loads(stream.getvalue().splitlines()[0])
        assert record["request_id"]

    def test_a_supplied_request_id_is_used(self) -> None:
        import io
        import logging

        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(JsonLogFormatter(service="ingestion"))
        logger = logging.getLogger("prognos.test.supplied")
        logger.handlers = [handler]
        logger.setLevel(logging.INFO)
        logger.propagate = False
        with RequestContext(request_id="req-42"):
            log_event(logger, "batch.accepted")
        assert json.loads(stream.getvalue().splitlines()[0])["request_id"] == "req-42"

    def test_a_new_context_generates_a_distinct_id(self) -> None:
        with RequestContext() as first:
            pass
        with RequestContext() as second:
            pass
        assert first.request_id != second.request_id

    def test_nested_contexts_restore_the_parent(self) -> None:
        """A swallowed exception must not leave the wrong id on later log lines."""
        with RequestContext(request_id="outer") as outer:
            try:
                with RequestContext(request_id="inner"):
                    raise RuntimeError("boom")
            except RuntimeError:
                pass
            assert outer.request_id == "outer"

    def test_metrics_render_as_prometheus_text(self) -> None:
        """The exposition format is a contract with Prometheus, not a free choice."""
        registry = MetricsRegistry(namespace="prognos")
        registry.counter("batches_total", "Batches seen", labels={"source": "simulator"})
        registry.counter("batches_total", "Batches seen", labels={"source": "simulator"})
        registry.gauge("coverage", "Live coverage", value=0.93)
        rendered = registry.render()
        assert 'prognos_batches_total{source="simulator"} 2.0' in rendered
        assert "prognos_coverage 0.93" in rendered
        assert "# TYPE prognos_batches_total counter" in rendered

    def test_a_counter_rejects_a_negative_increment(self) -> None:
        """A counter that can go down is not a counter."""
        registry = MetricsRegistry()
        registry.counter("things_total", "Things")
        with pytest.raises(ValueError, match="non-negative"):
            registry.counter("things_total", "Things", increment=-1)

    def test_metrics_include_the_stream_counters(self) -> None:
        """Stream rejects are the signal that ingestion is broken; they must be visible."""
        registry = MetricsRegistry(namespace="prognos")
        from prognos.stream.observability import record_stream_metrics

        stats = StreamStats()
        batch = TelemetryBatch(source="s", unit=1, rows=[])
        stats.record(batch, validate_batch(batch))
        record_stream_metrics(registry, stats)
        rendered = registry.render()
        assert "prognos_stream_batches_total" in rendered
        assert "prognos_stream_rejected_total" in rendered

    def test_a_span_records_its_duration_and_status(self) -> None:
        registry = MetricsRegistry(namespace="prognos")
        from prognos.stream.observability import span

        with span(registry, "window.materialise", unit=1):
            pass
        rendered = registry.render()
        assert "prognos_span_duration_seconds" in rendered
        assert "prognos_span_calls_total" in rendered

    def test_a_failing_span_is_recorded_as_an_error(self) -> None:
        """A trace that swallows the failure is worse than no trace."""
        registry = MetricsRegistry(namespace="prognos")
        from prognos.stream.observability import span

        with pytest.raises(RuntimeError), span(registry, "window.materialise", unit=1):
            raise RuntimeError("boom")
        assert "prognos_span_errors_total" in registry.render()


class TestRemainingBranches:
    """Coverage for the paths the earlier tests do not reach."""

    def test_batch_to_frame_uses_nan_for_missing_rows(self) -> None:
        """A missing cycle is unknown. Zero is a real measurement and would be averaged in."""
        from prognos.stream.events import Reading, TelemetryBatch

        batch = TelemetryBatch(
            source="s",
            unit=1,
            rows=[Reading(1, 0, 0, 1.0), Reading(1, 3, 1, 2.0)],
        )
        frame = batch.to_frame()
        assert frame.shape == (4, 18)
        assert frame[0, 0] == 1.0
        assert np.isnan(frame[1, 0]), "an absent channel must be NaN, not zero"
        assert np.isnan(frame[1, 0]), "a cycle with no reading must be NaN"
        assert np.isnan(frame[2, 0]), "a cycle with no reading must be NaN"
        assert frame[3, 1] == 2.0

    def test_an_empty_batch_has_an_empty_frame(self) -> None:
        from prognos.stream.events import TelemetryBatch

        assert TelemetryBatch(source="s", unit=1, rows=[]).to_frame().shape == (0, 18)

    def test_stream_metrics_reflect_each_reason_class(self) -> None:
        from prognos.stream.events import Reading
        from prognos.stream.observability import record_stream_metrics

        registry = MetricsRegistry(namespace="prognos")
        stats = StreamStats()
        stats.record(
            TelemetryBatch(source="s", unit=1, rows=[Reading(1, 0, 99, 1.0)]),
            validate_batch(TelemetryBatch(source="s", unit=1, rows=[Reading(1, 0, 99, 1.0)])),
        )
        record_stream_metrics(registry, stats)
        assert 'reason="channel_out_of_range"' in registry.render()

    def test_coverage_metrics_flag_a_breach_as_zero(self) -> None:
        """A breach has to be visible on a scrape, not only in a log line."""
        from prognos.stream.observability import record_coverage_metrics

        registry = MetricsRegistry(namespace="prognos")
        monitor = CoverageMonitor(target=0.9, min_samples=10)
        for observation in observations(False, 50):
            monitor.record(observation)
        record_coverage_metrics(registry, monitor.verdict())
        assert "prognos_interval_coverage_ok 0.0" in registry.render()

    def test_coverage_metrics_handle_the_undecided_state(self) -> None:
        """Not enough data must render as a number, not as a crash on None."""
        from prognos.stream.observability import record_coverage_metrics

        registry = MetricsRegistry(namespace="prognos")
        record_coverage_metrics(registry, CoverageMonitor(min_samples=50).verdict())
        assert "prognos_interval_coverage 0.0" in registry.render()

    def test_a_metric_cannot_change_its_type(self) -> None:
        """A name that is a counter in one service must not be a gauge in another."""
        registry = MetricsRegistry()
        registry.counter("shared_total", "Things")
        with pytest.raises(ValueError, match="already a"):
            registry.gauge("shared_total", "Things", value=1.0)
        registry.gauge("readings", "Readings", value=1.0)
        with pytest.raises(ValueError, match="already a"):
            registry.counter("readings", "Readings")

    def test_metrics_value_defaults_to_zero_for_an_unseen_series(self) -> None:
        assert MetricsRegistry().value("never_set") == 0.0

    def test_span_context_returns_none(self) -> None:
        from prognos.stream.observability import span

        registry = MetricsRegistry()
        with span(registry, "work") as value:
            assert value is None

    def test_alerting_lists_open_alerts_by_engine(self) -> None:
        service = AlertingService(threshold=20.0)
        service.evaluate(unit=3, cycle=1, lower=5.0, point=40.0)
        assert (None, 3) in service.alerts()
        assert service.open_alerts() == 1

    def test_predictor_repr_is_readable(self, tmp_path) -> None:
        predictor = fitted_predictor()
        predictor.save(tmp_path)
        assert "RulPredictor" in repr(RulPredictor.load(tmp_path))

    def test_load_rejects_a_calibrator_with_no_residuals(self, tmp_path) -> None:
        """Empty residuals cannot produce a width; refusing beats serving infinity."""
        predictor = fitted_predictor()
        predictor.save(tmp_path)
        (tmp_path / "calibrator.json").write_text(
            json.dumps({"target_coverage": 0.9, "calibration_residuals": [], "model": "m"})
        )
        with pytest.raises(ValueError, match="no calibration residuals"):
            RulPredictor.load(tmp_path)
