class TestAlerting:
    @staticmethod
    def _service(threshold: float = 20.0, hysteresis: float = 5.0) -> AlertingService:
        return AlertingService(threshold=threshold, hysteresis=hysteresis)

    def test_fires_when_the_lower_bound_crosses_the_threshold(self) -> None:
        service = self._service()
        alerts = service.evaluate(unit=1, cycle=100, lower=15.0, point=40.0)
        assert len(alerts) == 1
        assert alerts[0].kind == "maintenance_due"
        assert alerts[0].unit == 1

    def test_does_not_fire_above_the_threshold(self) -> None:
        service = self._service()
        assert service.evaluate(unit=1, cycle=100, lower=25.0, point=40.0) == []

    def test_fires_once_not_once_per_window(self) -> None:
        """A policy that alerts on every window is a policy nobody reads.

        Each engine holds at most one open maintenance alert until it resolves, which
        is what makes the alert a thing an operator can act on rather than a stream.
        """
        service = self._service()
        first = service.evaluate(unit=1, cycle=100, lower=15.0, point=40.0)
        second = service.evaluate(unit=1, cycle=110, lower=14.0, point=39.0)
        assert len(first) == 1
        assert second == [], "an engine already under alert must not alert again"

    def test_resolves_when_the_engine_recovers(self) -> None:
        """Hysteresis: a bound that flaps across the threshold must not flap the alert."""
        service = self._service(threshold=20.0, hysteresis=5.0)
        service.evaluate(unit=1, cycle=100, lower=15.0, point=40.0)
        # Back above the threshold, but not by enough to count as recovery.
        assert service.evaluate(unit=1, cycle=110, lower=22.0, point=40.0) == []
        # Clearly recovered.
        resolved = service.evaluate(unit=1, cycle=120, lower=30.0, point=40.0)
        assert [a.kind for a in resolved] == ["maintenance_resolved"]
        assert service.open_alerts(1) == 0

    def test_re_fires_after_resolving(self) -> None:
        service = self._service()
        service.evaluate(unit=1, cycle=100, lower=15.0, point=40.0)
        service.evaluate(unit=1, cycle=110, lower=30.0, point=40.0)
        again = service.evaluate(unit=1, cycle=120, lower=12.0, point=40.0)
        assert [a.kind for a in again] == ["maintenance_due"]

    def test_tracks_engines_independently(self) -> None:
        service = self._service()
        service.evaluate(unit=1, cycle=100, lower=15.0, point=40.0)
        other = service.evaluate(unit=2, cycle=100, lower=15.0, point=40.0)
        assert len(other) == 1
        assert service.open_alerts(2) == 1

    def test_an_alert_carries_the_numbers_an_operator_needs(self) -> None:
        service = self._service()
        alert = service.evaluate(unit=7, cycle=500, lower=12.0, point=33.0)[0]
        payload = alert.to_dict()
        assert payload["unit"] == 7
        assert payload["cycle"] == 500
        assert payload["lower"] == 12.0
        assert json.dumps(payload)

    def test_a_zero_threshold_is_allowed(self) -> None:
        """Only a negative threshold is incoherent; zero means "replace immediately"."""
        service = AlertingService(threshold=0.0)
        assert service.evaluate(unit=1, cycle=1, lower=0.0, point=0.0)

    def test_rejects_a_negative_threshold(self) -> None:
        with pytest.raises(ValueError, match="threshold"):
            AlertingService(threshold=-1.0)

    def test_rejects_hysteresis_below_zero(self) -> None:
        with pytest.raises(ValueError, match="hysteresis"):
            AlertingService(threshold=10.0, hysteresis=-1.0)


