"""Tests for serving, the S5 coverage monitor, alerting and observability.

The coverage monitor is the piece this project was missing. Phase 4 measured
calibration offline, on engines the model had never seen, generated by the same
simulator that trained it. Nothing in the pipeline watched whether that calibration
survived contact with a live stream, which is exactly what S5 exists to catch.

These tests are written against the failure modes rather than the happy path: a
monitor that judges too early, a monitor that hides a chronically uncovered engine
behind a healthy aggregate, and an alerting layer that either fires on every window
or never fires at all.
"""

from __future__ import annotations

import json

import numpy as np
import pytest

from prognos.stream.alerting import AlertingService
from prognos.stream.coverage import CoverageMonitor, Observation
from prognos.stream.events import StreamStats, TelemetryBatch, validate_batch
from prognos.stream.inference import RulPredictor
from prognos.stream.observability import (
    JsonLogFormatter,
    MetricsRegistry,
    RequestContext,
    log_event,
)

# ---------------------------------------------------------------- inference


def fitted_predictor(seed: int = 0) -> RulPredictor:
    """A small but real predictor: fitted on noise, calibrated on different noise."""
    rng = np.random.default_rng(seed)
    windows = rng.normal(size=(400, 20, 18)).astype(np.float32)
    cycles = np.arange(400, dtype=np.int64)
    targets = (100.0 - cycles / 10.0).astype(np.float32)

    calib_windows = rng.normal(size=(400, 20, 18)).astype(np.float32)
    calib_cycles = np.arange(400, dtype=np.int64)
    calib_targets = (100.0 - calib_cycles / 10.0).astype(np.float32)

    return RulPredictor.train(
        windows,
        cycles,
        targets,
        calib_windows,
        calib_cycles,
        calib_targets,
        target_coverage=0.9,
        seed=seed,
    )


class TestRulPredictor:
    def test_returns_one_interval_per_window(self) -> None:
        predictor = fitted_predictor()
        rng = np.random.default_rng(5)
        windows = rng.normal(size=(7, 20, 18)).astype(np.float32)
        intervals = predictor.predict(windows, np.arange(7, dtype=np.int64))
        assert len(intervals) == 7
        assert all(i.lower <= i.point <= i.upper for i in intervals)

    def test_interval_width_is_the_calibrated_half_width(self) -> None:
        """A band that is not the calibrated width means the calibrator is not applied."""
        predictor = fitted_predictor()
        rng = np.random.default_rng(6)
        windows = rng.normal(size=(5, 20, 18)).astype(np.float32)
        intervals = predictor.predict(windows, np.zeros(5, dtype=np.int64))
        for interval in intervals:
            assert interval.width == pytest.approx(2 * predictor._calibrator.width)

    def test_rejects_mismatched_lengths(self) -> None:
        predictor = fitted_predictor()
        rng = np.random.default_rng(7)
        with pytest.raises(ValueError, match="same length"):
            predictor.predict(
                rng.normal(size=(5, 20, 18)).astype(np.float32), np.zeros(3, np.int64)
            )

    def test_empty_batch_is_allowed(self) -> None:
        """No windows is a normal idle state, not an error."""
        predictor = fitted_predictor()
        assert predictor.predict(np.empty((0, 20, 18), np.float32), np.empty(0, np.int64)) == []

    def test_round_trips_through_disk(self, tmp_path) -> None:
        predictor = fitted_predictor()
        predictor.save(tmp_path)
        restored = RulPredictor.load(tmp_path)
        assert restored.target_coverage == pytest.approx(predictor.target_coverage)
        assert restored.model_name == predictor.model_name

        rng = np.random.default_rng(8)
        windows = rng.normal(size=(4, 20, 18)).astype(np.float32)
        cycles = np.arange(4, dtype=np.int64)
        assert [i.lower for i in restored.predict(windows, cycles)] == pytest.approx(
            [i.lower for i in predictor.predict(windows, cycles)]
        )

    def test_refuses_a_payload_with_no_calibrator(self, tmp_path) -> None:
        """The interval-free degradation must fail loudly, not serve a bare estimate.

        A model without its calibrator produces plausible predictions with no
        uncertainty attached, and the only symptom would be a dashboard with no
        bands — which reads as "nothing to report", not "something is broken".
        """
        predictor = fitted_predictor()
        predictor.save(tmp_path)
        (tmp_path / "calibrator.json").unlink()
        with pytest.raises(FileNotFoundError, match="calibrator"):
            RulPredictor.load(tmp_path)

    def test_refuses_a_payload_with_no_model(self, tmp_path) -> None:
        with pytest.raises(FileNotFoundError, match="model"):
            RulPredictor.load(tmp_path)


# ------------------------------------------------------------ S5 monitoring


def observations(covered: bool, n: int, unit: int = 1, spread: float = 1.0) -> list[Observation]:
    """`n` observations that are either all covered or all missed."""
    out = []
    for _ in range(n):
        truth = 50.0
        if covered:
            out.append(Observation(unit, truth, truth - spread, truth + spread, truth))
        else:
            out.append(Observation(unit, truth, truth + 10.0, truth + 20.0, truth - 5.0))
    return out


class TestCoverageMonitor:
    def test_refuses_to_judge_below_the_sample_floor(self) -> None:
        """Three predictions give a coin flip; declaring a breach would page on noise."""
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for observation in observations(True, 10):
            monitor.record(observation)
        verdict = monitor.verdict()
        assert verdict.status == "insufficient_data"
        assert verdict.measured is None
        assert not verdict.is_breach

    def test_healthy_coverage_reads_ok(self) -> None:
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for observation in observations(True, 200):
            monitor.record(observation)
        verdict = monitor.verdict()
        assert verdict.status == "ok"
        assert verdict.measured == pytest.approx(1.0)

    def test_a_breach_is_detected(self) -> None:
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for observation in observations(False, 200):
            monitor.record(observation)
        verdict = monitor.verdict()
        assert verdict.is_breach
        assert verdict.measured == pytest.approx(0.0)

    def test_coverage_just_inside_the_tolerance_is_not_a_breach(self) -> None:
        """The tolerance exists so a point or two of sampling noise does not page."""
        monitor = CoverageMonitor(target=0.9, tolerance=0.05, min_samples=50)
        total = 200
        missed = 12  # 94% coverage, comfortably inside 90% - 5pp
        for index in range(total):
            monitor.record(
                Observation(
                    1,
                    50.0,
                    49.0 if index >= missed else 51.0,
                    51.0 if index >= missed else 53.0,
                    50.0,
                )
            )
        verdict = monitor.verdict()
        assert verdict.measured == pytest.approx((total - missed) / total)
        assert verdict.status == "ok"

    def test_a_chronically_uncovered_engine_is_surfaced(self) -> None:
        """A healthy aggregate can hide one broken engine.

        S5 is defined on aggregate coverage, so the monitor reports that. An operator
        still needs to know which engine to look at when the aggregate is fine.
        """
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for index in range(400):
            # Engine 1 is always covered, engine 2 never is. Aggregate lands at 0.5,
            # which breaches anyway, so tighten the tolerance to isolate the case.
            monitor.record(
                Observation(
                    1,
                    50.0,
                    49.0,
                    51.0,
                    50.0,
                )
                if index % 2 == 0
                else Observation(2, 50.0, 60.0, 70.0, 45.0)
            )
        verdict = monitor.verdict()
        assert verdict.worst_engine == 2
        assert verdict.worst_coverage == pytest.approx(0.0)

    def test_engines_below_the_floor_do_not_set_the_worst_case(self) -> None:
        """One uncovered prediction on an engine would otherwise read as 0% coverage."""
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for index in range(200):
            monitor.record(Observation(1, 50.0, 49.0, 51.0, 50.0))
        monitor.record(Observation(2, 50.0, 60.0, 70.0, 45.0))
        verdict = monitor.verdict()
        assert verdict.worst_engine == 1
        assert verdict.worst_coverage == pytest.approx(1.0)

    def test_the_window_evicts_old_observations(self) -> None:
        """A breach that lasted a week must not be averaged back into compliance."""
        monitor = CoverageMonitor(target=0.9, min_samples=50, history=100)
        for observation in observations(False, 100):
            monitor.record(observation)
        for observation in observations(True, 100):
            monitor.record(observation)
        verdict = monitor.verdict()
        assert verdict.n_samples == 100
        assert verdict.status == "ok", "old breaches must be forgotten"

    def test_over_coverage_is_not_a_breach(self) -> None:
        """Over-covering is wasteful, not dangerous. It must not page anyone."""
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for observation in observations(True, 200):
            monitor.record(observation)
        assert monitor.verdict().status == "ok"

    def test_rejects_a_history_shorter_than_the_floor(self) -> None:
        """The monitor must not be constructible into never reaching a verdict."""
        with pytest.raises(ValueError, match="sample floor"):
            CoverageMonitor(min_samples=50, history=10)

    def test_rejects_a_nonsense_target_or_tolerance(self) -> None:
        with pytest.raises(ValueError, match="target coverage"):
            CoverageMonitor(target=1.5)
        with pytest.raises(ValueError, match="tolerance"):
            CoverageMonitor(tolerance=0.0)

    def test_reports_error_per_engine_alongside_coverage(self) -> None:
        """Coverage alone does not say whether the predictions are any good."""
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for index in range(100):
            offset = 1.0 if index < 50 else 10.0
            monitor.record(Observation(1, 50.0, 49.0, 51.0, 50.0 - offset))
        errors = monitor.error_by_engine()
        assert errors[1] > 0.0

    def test_verdict_is_serialisable_for_the_metrics_endpoint(self) -> None:
        monitor = CoverageMonitor(target=0.9, min_samples=50)
        for observation in observations(True, 100):
            monitor.record(observation)
        payload = monitor.verdict().to_dict()
        assert payload["status"] == "ok"
        assert json.dumps(payload)


